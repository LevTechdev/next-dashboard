for (const locale of ["en", "id", "zh", "ja"]) {
  const file = path.join(LOCALES_DIR, `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  let added = 0;

  if (!data.nav) data.nav = {};
  if (!Object.prototype.hasOwnProperty.call(data.nav, "affiliates")) {
    data.nav.affiliates = NAV[locale];
    added++;
  }

  if (!data.affiliates) data.affiliates = {};
  for (const [k, v] of Object.entries(AFF[locale])) {
    if (!Object.prototype.hasOwnProperty.call(data.affiliates, k)) {
      data.affiliates[k] = v;
      added++;
    }
  }

  fs.writeFileSync(file, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`${locale}.json: +${added} keys`);
}
