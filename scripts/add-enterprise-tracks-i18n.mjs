for (const loc of LOCALES) {
  const filePath = path.join(LOCALES_DIR, `${loc}.json`);
  const content = JSON.parse(fs.readFileSync(filePath, "utf8"));

  // 1. Add copilotActions
  content.copilotActions = translations.copilotActions[loc];

  // 2. Add inboundWebhooks
  content.inboundWebhooks = translations.inboundWebhooks[loc];

  // 3. Add compliance
  content.compliance = translations.compliance[loc];

  // 4. Add tabOmnichannel to integrations namespace
  if (content.integrations) {
    content.integrations.tabOmnichannel = tabOmnichannel[loc];
  }

  fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + "\n", "utf8");
  console.log(`Updated translations for locale: ${loc}`);
}

